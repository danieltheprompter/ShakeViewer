let currentLang = 'en';

export function t(key, params) {
  let s = TRANSLATIONS[currentLang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = String(s).replaceAll(`{${k}}`, v);
  return s;
}

export function setLang(lang) {
  currentLang = LANGUAGES[lang] ? lang : 'en';
  try { localStorage.setItem('sv_lang', currentLang); } catch { /* ignore */ }
  if (typeof document !== 'undefined') document.documentElement.lang = currentLang;
  return currentLang;
}

export function getLang() { return currentLang; }

export function initLang() {
  try {
    const s = localStorage.getItem('sv_lang');
    if (s && LANGUAGES[s]) return setLang(s);
  } catch { /* ignore */ }
  const n = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2);
  return setLang(LANGUAGES[n] ? n : 'en');
}

export { LANGUAGES, TRANSLATIONS };
